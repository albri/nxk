// Questions about who exists, answered from the generated people shipped with a country's map. No request is made,
// no decision model is asked, and it costs nothing.
//
//   node scripts/people.ts fields  --country=uk                          every field, one line each (to choose what a scan asks about)
//   node scripts/people.ts find    --country=uk --word=smartphone        fields and values that mention a word
//   node scripts/people.ts values  --country=uk --field=home_tenure      the values a field can take
//   node scripts/people.ts count   --country=uk --who=age_years=18..34,home_tenure=rented_from_a_private_landlord_or_letting_agency
//   node scripts/people.ts split   --country=uk --who=age_years=18..34 --by=home_tenure,life_stage
//   node scripts/people.ts reach   --country=uk --need=internet_use_frequency=daily_or_almost_daily,devices_used_to_go_online=smartphone
//   node scripts/people.ts profile --country=uk --who=financial_risk_tolerance=not_willing_to_take_any_financial_risk
//   node scripts/people.ts cast    --country=uk --pictured=age_years=25..44,confidence_using_digital_devices_and_apps=very_confident
//   node scripts/people.ts meet    --country=uk --who=home_tenure=rented_from_a_private_landlord_or_letting_agency --n=6
//
//   --who     the group: conditions joined by commas, all of which must hold
//   --need    for reach: requirements applied one after another, in the order given
//   --among   the audience to work within, in place of all adults (same form as --who)
//   --pictured  for cast: the person you had in mind; the people are drawn from everyone else (--n=12, --seed=1, --show=field)
//   --people  another people file (from scripts/pull.ts), in place of the shipped one
//   --unit=firms  for count and split: the firms these people work for, in place of adults, by facts about the firm
//             node scripts/people.ts count --country=uk --unit=firms --who=organisation_size=10_to_49_employees,region=north_west
//   A value can be several codes joined with "|"; a numeric field takes a range such as 18..34.
//
// The people are generated by PersonaGen. Each field has a tier: A is fitted to official statistics, B to other
// surveys, C is modelled. A link between two tier A facts is close to measured; one involving a tier C fact is
// PersonaGen's modelling. Shares come with a margin; under about 100 people treat a line as a lead. A fact PersonaGen
// ties to occupation only by broad group (the map's occupation_ties: in the UK shift work, job level and income, among
// others, by major group) has that group's rate in every occupation within it, so a count, split or profile that reads
// one for a narrower occupation says so (scripts/occupation-ties.ts).
//
// Firms are counted from each person's firm weight (1 divided by the number of people at their employer; a one-person
// business is 1): summed over the people a fact about their firm picks, the weights count the firms with it. A firm
// count says firms in every line, and an adult count never does (scripts/businesses.ts FIRM_FACT, notAboutFirms).
