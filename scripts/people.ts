const round2 = (x: number) => {
  if (x < 100) return String(Math.round(x));
  const p = 10 ** (Math.floor(Math.log10(x)) - 1);
  return (Math.round(x / p) * p).toLocaleString("en-GB");
};

/** About how many real adults a group of n generated people of `total` is, with the give-or-take of the draw. */
export function adultsLine(n: number, total: number, country: Country): string {
  const adults = ADULTS[country];
  if (!adults || !total) return "";
  const p = n / total;
  const plusMinus = 2 * Math.sqrt((p * (1 - p)) / total) * adults.n;
  return `about ${round2(p * adults.n)} of the adults in the ${country.toUpperCase()} (give or take ${round2(plusMinus)}; the share of the generated people times the ${adults.source})`;
}

/**
 * A count of firms as said: "about 59,000 firms", from the sum of the firm weights of a group of the `total`
 * generated people. Always "firms", so that it is never read as a number of adults.
 */
export function firmsLine(sum: number, total: number, country: Country): string {
  const firms = firmsIn(sum, total, country);
  return firms < 0.5 ? "no firms" : `about ${round2(firms)} firm${round2(firms) === "1" ? "" : "s"}`;
}

/** A group's share of the firms it is counted among, rounded: "22 in every 100 of the firms". */
export function firmShare(part: number, whole: number): string {
  const p = whole ? part / whole : 0;
  if (p >= 0.995) return "all of the firms";
  return p < 0.005 ? "under 1 in every 100 of the firms" : `${Math.round(100 * p)} in every 100 of the firms`;
}

