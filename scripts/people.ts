/** A label as it reads inside a sentence: "Care Workers And Home Carers" is "care workers and home carers". */
function inline(text: string) {
  const words = text.split(" ");
  const small = /^(and|of|the|in|for|or|to|n\.e\.c\.)$/;
  const title =
    words.length > 1 &&
    words.filter((w) => !small.test(w)).every((w) => !/^[a-z]/.test(w)) &&
    words.slice(1).some((w) => /^[A-Z][a-z]/.test(w));
  if (title) return text.toLowerCase();
  return /^[A-Z][a-z]/.test(text) && !/^[A-Z][a-z]+ [A-Z]/.test(text)
    ? text.charAt(0).toLowerCase() + text.slice(1)
    : text;
}

/**
 * A card's place, from its settlement, county and region, each said once. A US place and county carry their state
 * ("Livonia city, Michigan", "Wayne County, Michigan"), which the region says again, and a census type ("city",
 * "CDP"): each part loses a name a later part gives, and its type. Livonia, Wayne County, Michigan.
 */
export function placeLine(parts: string[]): string[] {
  const key = (t: string) => t.toLowerCase().replace(/[^a-z]/g, "");
  return parts
    .map((part, j) => {
      let text = part;
      for (const later of parts.slice(j + 1))
        if (text.endsWith(`, ${later}`)) text = text.slice(0, -(later.length + 2));
      return text.replace(/ (city|town|village|CDP|borough|township|municipality)$/, "");
    })
    .filter((t, j, all) => all.findIndex((u) => key(u) === key(t)) === j);
}

/**
 * The values a group is drawn on, by field name, as a card writes them: interest_families=team_racket_and_social_sports
 * gives interest_families → {"Team racket and social sports"}. A range or a "not" names no value, and gives none.
 */
export function groupReasons(fields: Field[], conditions: Condition[]): Map<string, Set<string>> {
  const reasons = new Map<string, Set<string>>();
  const add = (name: string, value: { code: string; label?: string }) => {
    const texts = reasons.get(name) ?? new Set<string>();
    texts.add(sheetText(value.label ?? value.code));
    reasons.set(name, texts);
  };
  const interests = fields.find((f) => f.name === "interests");
  for (const condition of conditions) {
    const field = fields.find((f) => f.path === condition.path);
    const codes = condition.codes ?? [];
    if (!field?.values || !codes.length) continue;
    for (const value of field.values) if (codes.includes(value.code)) add(field.name, value);
    // A family of interests holds specific ones (football playing, ten pin bowling): theirs come first among them.
    if (/^interest_(families|participation)$/.test(field.name))
      for (const value of interests?.values ?? [])
        if (Array.isArray(value.as) && value.as.some((a) => "family" in a && codes.includes(a.family ?? "")))
          add("interests", value);
  }
  return reasons;
}

/** People to meet: drawn at random from inside the group, each as a card of their own facts. Colour, not evidence. */
function printMeet(log: Log, fields: Field[], { among, base, all }: Audience, group: Group, flags: Flags) {
  const within = group.conditions.length ? group.members : all;
  const where = group.conditions.length
    ? `people who are ${group.name}`
    : among.length
      ? `people in this audience (${describeConditions(among)})`
      : "adults";
  const n = Math.min(Number(flags.n ?? 6), 12);
  if (within.length < n) log.line(`Only ${within.length} generated ${where}: every one is shown.`);
  const picked = draw(within, n, flags.seed ?? 1);
  const drawnFrom = group.conditions.length ? `people (${group.name})` : inline(where);
  log.line(
    [
      `${picked.length} of ${within.length} generated ${drawnFrom}, drawn at random (another seed draws another set).`,
      "Each card is one person's own facts, which hang together; it is an example from the group, not a summary of it.\n",
    ].join(" "),
  );
  const texts = (row: Row, names: string[]) => sheet(fields, row, { always: names }).always;
  const reasons = groupReasons(fields, group.conditions);
  const onCard = new Set(CARD.flatMap(([, names]) => names));
  picked.forEach((i, k) => {
    const row = base[i];
    const head = texts(row, ["gender", "age_years"]).map((e) => e.text);
    const place = placeLine(texts(row, ["settlement_name", "county_or_local_authority", "region"]).map((e) => e.text));
    log.line(`${k + 1}. ${head.join(", ")}. ${place.join(", ")}.`);
    // What put the person in the group comes first in its section and is never cut (a card shows five interests),
    // or has a line of its own when the card has no section for it (a family of interests), so every card shows it.
    const why = (e: { name: string; text: string }) => reasons.get(e.name)?.has(e.text) ?? false;
    const elsewhere = texts(
      row,
      [...reasons.keys()].filter((name) => !onCard.has(name)),
    ).filter(why);
    if (elsewhere.length) log.line(`   In the group for: ${elsewhere.map((e) => inline(e.text)).join("; ")}.`);
    for (const [title, names] of CARD) {
      const seen: Record<string, number> = {};
      const parts = texts(row, names)
        .sort((a, b) => names.indexOf(a.name) - names.indexOf(b.name) || Number(why(b)) - Number(why(a)))
        .filter((e) => why(e) || (!EMPTY.test(e.text) && !QUINTILE.test(e.text)))
        .filter((e) => (seen[e.name] = (seen[e.name] ?? 0) + 1) <= (MOST[e.name] ?? 99) || why(e))
        .map((e) => {
          const text = inline(e.text);
          return ABOUT[e.name] && !/^no\b/i.test(text) && !text.startsWith(ABOUT[e.name].trim())
            ? ABOUT[e.name] + text
            : text;
        });
      if (title === "Not working" && texts(row, ["current_occupation"]).length) continue;
      if (parts.length) log.line(`   ${title}: ${parts.join("; ")}.`);
    }
    log.line("");
  });
  log.line(
    [
      "Generated by PersonaGen, not real individuals: each person's facts fit together,",
      "and as a group they match official statistics; attitudes and personality are modelled.",
      "A card is an example, never evidence about the group: the group's figures come from count, split and profile.",
      `Anything written in a person's voice, such as what they would say or do, is imagined: mark it "imagined", and give it no figures.`,
    ].join(" "),
  );
}

/** One group's size within the audience. */
function printCount(log: Log, { whole, sized }: Audience, group: Group) {
  if (!group.conditions.length) throw new Error("Give who: one condition or more");
  log.line(`Within ${whole}:\n${group.name}: ${sized(group.members.length)}.`);
  if (group.conditions.some((c) => ROLE.test(c.path))) log.line(`\n${ROLE_NOTE}`);
}

/** Fields broken down within the group (or the audience), each value's share of it against the audience's. */
function printSplit(
  log: Log,
  fields: Field[],
  { among, base, all, whole, sized }: Audience,
  group: Group,
  flags: Flags,
) {
  if (!flags.by) throw new Error("Give by: one field or more");
  log.line(
    `${group.conditions.length ? `${group.name}: ${sized(group.members.length)}` : `Everyone in ${whole}`}. Share of the group, then of ${among.length ? "the audience" : "all adults"}:`,
  );
  const within = group.conditions.length ? group.members : all;
  for (const by of list(flags.by)) {
    const f = fields.findIndex((field) => field.name === by || field.path === by);
    if (f < 0)
      throw new Error(
        `No field "${by}". Nearest: ${nearestFields(fields, by)}. A number such as age_years splits into bands.`,
      );
    log.line(`\n${fields[f].path} [${tierLabel(fields[f].tier)}]`);
    // A long list is cut to the values the group holds most; the rest are counted in one line.
    const lines = split(fields[f], f, base, within, all).filter(
      (line) => line.numeric || line.group >= 0.005 || line.all >= 0.005,
    );
    // A numeric field's few lines are never cut; its middle value, null when nobody has one, would sort as 0.
    const shown =
      lines.length > SPLIT_MOST
        ? [...lines].sort((a, b) => (b.group ?? 0) - (a.group ?? 0)).slice(0, SPLIT_MOST)
        : lines;
    for (const line of shown) {
      if (line.numeric) log.line(`  middle value ${line.group} against ${line.all}`);
      else log.line(`  ${percent(line.group).padStart(4)}  ${percent(line.all).padStart(4)}  ${line.label}`);
    }
    if (lines.length > shown.length)
      log.line(`  and ${lines.length - shown.length} more values held by 1 in 200 or more of either.`);
  }
  if (within.length < 100) log.line(`\nOnly ${within.length} people in the group: a lead, not a finding.`);
}

/** Requirements applied one after another: how many remain after each, then who the ones who cannot be reached are. */
function printReach(log: Log, fields: Field[], { among, base, whole }: Audience, flags: Flags) {
  const needs = conditionsOf(fields, list(flags.need));
  if (!needs.length) throw new Error("Give need: one condition or more");
  const result = reach(base, needs);
  log.line(`Of every 100 in ${whole}:`);
  for (const step of result.steps)
    log.line(`  ${per100(step.left / result.start).padStart(5)} remain after: ${step.text}`);
  const left = result.in.length / result.start;
  log.line(
    `So ${per100(left)} in every 100 can be reached (give or take ${giveOrTake(left, result.start)}) and ${per100(1 - left)} cannot.`,
  );
  if (result.out.length >= 30 && result.in.length >= 30) {
    log.line(`\nThe ones who cannot, against ${among.length ? "the audience" : "all adults"}:`);
    const out = new Set(result.out);
    printMarks(
      log,
      fields,
      base,
      base.map((_, i) => out.has(i)),
      new Set(needs.map((c) => c.path)),
      flags,
    );
  }
  log.line("\nTiers: A fitted to official statistics, B to other surveys, C modelled.");
}

/** What marks the group out from the audience, section by section. */
function printProfile(log: Log, fields: Field[], { among, base, sized }: Audience, group: Group, flags: Flags) {
  if (!group.conditions.length) throw new Error("Give who: one condition or more");
  log.line(`${group.name}: ${sized(group.members.length)}.`);
  if (group.members.length < 100)
    log.line(
      `Only ${group.members.length} people: treat every line as a lead${group.members.length < 30 ? ", and nothing below is dependable" : ""}.`,
    );
  if (!group.members.length) return;
  log.line(
    `Share of this group against share of ${among.length ? "the audience" : "all adults"}; a line is shown when the gap is real (4 standard errors) and wide enough.\n`,
  );
  const inGroup = new Set(group.members);
  printMarks(
    log,
    fields,
    base,
    base.map((_, i) => inGroup.has(i)),
    new Set(group.conditions.map((c) => c.path)),
    flags,
  );
  log.line(
    "\nTiers: A fitted to official statistics, B to other surveys, C modelled. Generated people, not a survey: use this to recognise and reach the group, and check anything you will spend money on.",
  );
}

/** The lines of a profile worth printing, under their sections, without the fields in `skip` (the ones asked about). */
function printMarks(log: Log, fields: Field[], base: Row[], inGroup: boolean[], skip: Set<string>, flags: Flags) {
  const sections = new Map<string, ProfileLine[]>();
  for (const line of profile(fields, base, inGroup)) {
    if (skip.has(line.path)) continue;
    const title = TITLES[line.path.split(".")[0]] ?? line.path.split(".")[0];
    if (!sections.has(title)) sections.set(title, []);
    sections.get(title)!.push(line);
  }
  for (const [title, lines] of sections) {
    const numbers = lines.filter((line) => line.numeric && line.group !== null && line.group !== line.all);
    const kept = marked(lines, { gap: Number(flags.gap ?? 5) / 100, top: Number(flags.top ?? 12) });
    if (!numbers.length && !kept.length) continue;
    log.line(title);
    for (const line of numbers)
      log.line(
        `  ${line.path.split(".")[1]}: middle value ${line.group} against ${line.all}  [${tierLabel(line.tier)}]`,
      );
    for (const line of kept) {
      log.line(
        `  ${line.gap > 0 ? "more" : "less"}  ${percent(line.group).padStart(4)} against ${percent(line.all).padStart(4)}  ${line.path.split(".")[1]}: ${line.label}  [${tierLabel(line.tier)}]`,
      );
      // What marks the group out, for the next step the server names (mcp/nudge.ts): the gap as printed.
      log.record("marked", {
        field: line.path.split(".")[1],
        gap: Math.abs(Math.round(100 * line.group) - Math.round(100 * line.all)),
      });
    }
  }
}

